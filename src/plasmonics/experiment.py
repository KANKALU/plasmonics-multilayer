"""Reading and aligning the goniometer measurements.

Each measurement file holds one whitespace-separated row of relative
reflectance, already normalised against a reference taken below the
critical angle.  The angular axis is not stored in the file: it is the
goniometer sweep, 20 to 80 degrees in 0.1 degree steps, 601 points.

The mounting has a small unknown angular offset, so the measured curve is
aligned to the model by putting the BK7/air critical angle, located as
the steepest point of the smoothed curve, at exactly 41 degrees.  This is
a rigid shift of the angle axis; the reflectance values are untouched.

Raw measurement files are not distributed with this repository.  The
loaders are kept so the processing chain is auditable, and so the figures
can be regenerated by anyone holding the data.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from scipy.signal import savgol_filter

from .samples import ANGLE_SWEEP_DEG, THETA_CRITICAL_DEG

__all__ = ["angle_axis", "load_measurement", "find_critical_angle", "align_to_model"]


def angle_axis(sweep=ANGLE_SWEEP_DEG) -> np.ndarray:
    """The goniometer angular axis, in degrees."""
    start, stop, step = sweep
    return np.round(np.arange(start, stop + step / 2, step), 10)


def load_measurement(path: str | Path, sweep=ANGLE_SWEEP_DEG) -> tuple[np.ndarray, np.ndarray]:
    """Read one measurement file.

    Returns ``(theta_deg, R)``.  Raises if the point count disagrees with
    the sweep, which is the only guard against a file whose angular range
    differs from the nominal one.
    """
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    R = np.fromstring(text.replace("\t", " "), sep=" ")
    if R.size == 0:
        raise ValueError(f"{path}: no numeric data")

    theta = angle_axis(sweep)
    if R.size != theta.size:
        raise ValueError(f"{path}: {R.size} points do not match the {theta.size}-point sweep")
    return theta, R


def find_critical_angle(
    theta: np.ndarray,
    R: np.ndarray,
    search_window=(37.0, 43.0),
    window: int = 21,
    polyorder: int = 3,
) -> float:
    """Locate the critical angle as the steepest point of the curve.

    The measurement is smoothed with a Savitzky-Golay filter before
    differentiating, because the raw curve is noisy enough that the
    numerical derivative would otherwise pick a noise spike.  The search
    is restricted to a window around the expected value so that a deep
    plasmon minimum elsewhere cannot win.
    """
    if window % 2 == 0:
        window += 1
    R_smooth = savgol_filter(R, window, polyorder)
    dR = np.gradient(R_smooth, theta)

    lo, hi = search_window
    mask = (theta >= lo) & (theta <= hi)
    if not mask.any():
        raise ValueError(f"search window {search_window} lies outside the sweep")
    return float(theta[mask][int(np.argmax(np.abs(dR[mask])))])


def align_to_model(
    theta: np.ndarray,
    R: np.ndarray,
    theta_reference: float = THETA_CRITICAL_DEG,
    **kwargs,
) -> tuple[np.ndarray, float]:
    """Shift the angle axis so the measured critical angle lands on the model's.

    Returns ``(theta_shifted, offset)``.  The offset is reported so it can
    be quoted alongside a figure: a shift of more than a degree or so
    means the mounting, not the sample, deserves the attention.
    """
    theta_c = find_critical_angle(theta, R, **kwargs)
    offset = theta_reference - theta_c
    return theta + offset, offset


def parse_filename(name: str) -> dict:
    """Pull sample, polarisation and wavelength out of a measurement filename.

    Files are named like ``m7S_700_Norm_Air.txt``: sample ``m7``,
    polarisation ``S`` (TE) or ``P`` (TM), wavelength in nanometres, and
    ``Norm_Air`` marking the normalisation reference.
    """
    stem = Path(name).stem
    head = stem.split("_")[0]
    sample = head[:-1].upper()
    pol_letter = head[-1].upper()
    if pol_letter not in ("P", "S"):
        raise ValueError(f"{name}: cannot read polarisation from {head!r}")

    lam_nm = None
    for part in stem.split("_")[1:]:
        if part.isdigit():
            lam_nm = int(part)
            break

    return {
        "sample": sample,
        "pol": "p" if pol_letter == "P" else "s",
        "polarisation": "TM" if pol_letter == "P" else "TE",
        "wavelength_nm": lam_nm,
    }
